#!/usr/bin/env bash
set -euo pipefail

# generate_daily_commit.sh
# Creates a small update in daily_updates/, commits it with the supplied author,
# and optionally pushes. Uses Conventional Commit style with a `daily` scope.

usage() {
  cat <<EOF
Usage: $0 --name "Full Name" --email "email@example.com" [--type feat|fix|docs|chore] [--push]

Options:
  --name    Commit author name (required)
  --email   Commit author email (required)
  --type    Commit type (default: chore)
  --push    If provided, runs 'git push' after committing (requires credentials)
  --help    Show this message
EOF
}

NAME=""
EMAIL=""
TYPE="chore"
PUSH=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --name) NAME="$2"; shift 2;;
    --email) EMAIL="$2"; shift 2;;
    --type) TYPE="$2"; shift 2;;
    --push) PUSH=1; shift 1;;
    --help) usage; exit 0;;
    *) echo "Unknown arg: $1" >&2; usage; exit 1;;
  esac
done

if [[ -z "$NAME" || -z "$EMAIL" ]]; then
  echo "--name and --email are required" >&2
  usage
  exit 2
fi

BRANCH=$(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo "main")

mkdir -p daily_updates
FILE="daily_updates/$(date +%Y-%m-%d)-note.md"

MESSAGES=(
  "Refined API docs for daily run"
  "Minor cleanup in examples"
  "Add reproducible demo snippet"
  "Update dependency notes"
  "Improve README section about quickstart"
)

MSG=${MESSAGES[$((RANDOM % ${#MESSAGES[@]}))]}

cat > "$FILE" <<EOF
# Daily update: $(date -I)

- $MSG

Generated by generate_daily_commit.sh
EOF

git add "$FILE"

COMMIT_MSG="$TYPE(daily): $MSG - $(date +%Y-%m-%d)"

# Use explicit author for this commit so it shows the provided name/email
GIT_AUTHOR_NAME="$NAME" GIT_AUTHOR_EMAIL="$EMAIL" git commit -m "$COMMIT_MSG" --author="$NAME <$EMAIL>" || {
  echo "No changes to commit or commit failed." >&2
  exit 3
}

echo "Committed: $COMMIT_MSG on branch $BRANCH as $NAME <$EMAIL>"

if [[ $PUSH -eq 1 ]]; then
  echo "Attempting to push to origin/$BRANCH..."
  git push origin "$BRANCH"
fi
